// Writes design/CANVAS-MAP.md from design/canvas/canvas.json: every canvas page,
// its sections (the title notes on that page) and the artboards in each, in order.
// Agents read the map first, then open only the artboards for their feature.
// Run after every canvas mirror: `pnpm canvas:map`.
import { readFileSync, writeFileSync } from 'node:fs';

const CANVAS_URL = 'https://claude.ai/artifact/1sFjCeUornYw7f8rReZBtJ';
const root = new URL('../design/', import.meta.url);

interface Board { x: number; y: number; w: number; h: number; title?: string; page?: string }
interface Note { x: number; y: number; text: string; kind?: string; page?: string }
interface Canvas { pages?: { id: string; name: string }[]; boards: Record<string, Board>; notes?: Record<string, Note> }

const canvas = JSON.parse(readFileSync(new URL('canvas/canvas.json', root), 'utf8')) as Canvas;
const pages = canvas.pages ?? [];
const firstPage = pages[0]?.id;
const stem = (file: string) => file.replace(/\.dc\.html$/, '');
const anchor = (s: string) => s.replace(/\.dc\.html$/, '').replace(/[^A-Za-z0-9_-]/g, '-');

const lines = [
  '# Canvas map',
  '',
  `Generated by \`pnpm canvas:map\` from [canvas/canvas.json](canvas/canvas.json). Do not edit by hand.`,
  '',
  `Canvas: ${CANVAS_URL}. One page per feature; open a page with \`${CANVAS_URL}#page-<id>\`, an artboard with \`#artboard-<name>\`.`,
  'Read this map first, then only the `.dc.html` files your task names (most are a few lines that mount a large component such as `Main` or `DocsPage` with props). Status lives in [INVENTORY.md](INVENTORY.md).',
  '',
];

for (const page of pages) {
  const boards = Object.entries(canvas.boards)
    .filter(([, b]) => (b.page ?? firstPage) === page.id)
    .sort(([, a], [, b]) => a.y - b.y || a.x - b.x);
  const sections = Object.values(canvas.notes ?? {})
    .filter((n) => n.kind === 'title1' && n.page === page.id && n.y >= 0)
    .sort((a, b) => a.y - b.y);
  lines.push(`## ${page.name} · \`${page.id}\` · ${boards.length} artboards`, '');
  let current = -1;
  for (const [file, b] of boards) {
    let section = -1;
    sections.forEach((s, i) => { if (s.y <= b.y) section = i; });
    if (section !== current) {
      current = section;
      lines.push('', `**${sections[section]?.text.split('\n')[0] ?? 'Artboards'}**`, '');
    }
    const title = b.title ? ` — ${b.title.replace(/^Pasodrum work — /, '')}` : '';
    lines.push(`- [${stem(file)}](canvas/${file})${title} \`#artboard-${anchor(file)}\``);
  }
  lines.push('');
}

writeFileSync(new URL('CANVAS-MAP.md', root), lines.join('\n').replace(/\n{3,}/g, '\n\n'));
console.log(`design/CANVAS-MAP.md: ${pages.length} pages, ${Object.keys(canvas.boards).length} artboards`);
